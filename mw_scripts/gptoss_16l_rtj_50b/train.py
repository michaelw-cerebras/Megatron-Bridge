"""Pretrain the custom 16-layer GPT-OSS variant on the RTJ PT 50B blend."""

from __future__ import annotations

import argparse
import json
import logging
import math
import os
from pathlib import Path

from megatron.bridge.training.gpt_step import forward_step
from megatron.bridge.training.pretrain import pretrain
from mw_scripts.mini_gptoss import (
    GPT_OSS_PAD_TOKEN_ID,
    GPT_OSS_TOKENIZER,
    _build_gpt_oss_20b_config,
    _gpt_oss_transformer_layer_spec,
)


LOGGER = logging.getLogger(__name__)


def _positive_int(value: str) -> int:
    parsed = int(value)
    if parsed < 1:
        raise argparse.ArgumentTypeError("value must be at least 1")
    return parsed


def _nonnegative_int(value: str) -> int:
    parsed = int(value)
    if parsed < 0:
        raise argparse.ArgumentTypeError("value must be nonnegative")
    return parsed


def parse_args() -> argparse.Namespace:
    """Parse full pretraining arguments."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--hf-model", required=True, type=Path)
    parser.add_argument("--dataset-root", required=True, type=Path)
    parser.add_argument(
        "--data-args-path",
        required=True,
        type=Path,
        help="Whitespace-delimited Megatron weight/prefix pairs generated by build_megatron_mixture.py.",
    )
    parser.add_argument("--train-tokens", type=_positive_int, default=50_000_000_000)
    parser.add_argument("--seq-length", type=_positive_int, default=8192)
    parser.add_argument("--micro-batch-size", type=_positive_int, default=1)
    parser.add_argument("--global-batch-size", type=_positive_int, default=128)
    parser.add_argument("--tensor-parallel", type=_positive_int, default=1)
    parser.add_argument("--pipeline-parallel", type=_positive_int, default=1)
    parser.add_argument("--expert-parallel", type=_positive_int, default=8)
    parser.add_argument("--expert-tensor-parallel", type=_positive_int, default=1)
    parser.add_argument("--num-workers", type=_nonnegative_int, default=2)
    parser.add_argument("--dataset-cache-dir", type=Path)
    parser.add_argument("--lr", type=float, default=3e-4)
    parser.add_argument("--min-lr", type=float, default=3e-5)
    parser.add_argument("--lr-warmup-iters", type=_nonnegative_int, default=1000)
    parser.add_argument(
        "--lr-decay-style",
        choices=("constant", "linear", "cosine", "inverse-square-root"),
        default="cosine",
    )
    parser.add_argument(
        "--precision",
        choices=("bf16", "fp8-current", "mxfp8"),
        default="fp8-current",
    )
    parser.add_argument(
        "--no-full-recompute",
        action="store_true",
        help="Disable the full activation recomputation enabled by default.",
    )
    parser.add_argument("--save-dir", required=True, type=Path)
    parser.add_argument("--resume-checkpoint", type=Path)
    parser.add_argument("--save-interval", type=_positive_int, default=5000)
    parser.add_argument("--tensorboard-dir", required=True, type=Path)
    parser.add_argument("--log-interval", type=_positive_int, default=10)
    return parser.parse_args()


def _load_data_args(dataset_root: Path, data_args_path: Path) -> tuple[list[str], int]:
    """Validate the tokenizer manifest and weighted indexed-dataset prefixes."""
    dataset_root = dataset_root.expanduser().resolve()
    data_args_path = data_args_path.expanduser().resolve()
    manifest_path = dataset_root / "manifest.json"
    if not manifest_path.is_file():
        raise FileNotFoundError(manifest_path)
    if not data_args_path.is_file():
        raise FileNotFoundError(data_args_path)

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    tokenizer = manifest.get("tokenizer")
    if not isinstance(tokenizer, dict):
        raise ValueError(f"Missing tokenizer metadata in {manifest_path}")
    if tokenizer.get("id") != GPT_OSS_TOKENIZER:
        raise ValueError(f"Dataset used tokenizer {tokenizer.get('id')!r}; expected {GPT_OSS_TOKENIZER!r}.")

    data_args = data_args_path.read_text(encoding="utf-8").split()
    if not data_args or len(data_args) % 2:
        raise ValueError(f"Expected weight/prefix pairs in {data_args_path}")

    weights: list[float] = []
    prefixes: list[str] = []
    for index in range(0, len(data_args), 2):
        raw_weight = data_args[index]
        prefix = data_args[index + 1]
        try:
            weight = float(raw_weight)
        except ValueError as error:
            raise ValueError(f"Invalid blend weight {raw_weight!r} in {data_args_path}") from error
        if not math.isfinite(weight) or weight <= 0:
            raise ValueError(f"Blend weights must be finite and positive, got {raw_weight!r}")
        for suffix in (".bin", ".idx"):
            dataset_file = Path(f"{prefix}{suffix}")
            if not dataset_file.is_file():
                raise FileNotFoundError(dataset_file)
        weights.append(weight)
        prefixes.append(prefix)

    if len(prefixes) != len(set(prefixes)):
        raise ValueError(f"Duplicate dataset prefixes found in {data_args_path}")
    if not math.isclose(sum(weights), 1.0, rel_tol=0.0, abs_tol=1e-9):
        raise ValueError(f"Blend weights sum to {sum(weights):.17g}, expected 1.0")
    return data_args, int(tokenizer["eos_id"])


def _validate_parallelism(args: argparse.Namespace) -> None:
    """Validate the configured parallel dimensions against torchrun's world size."""
    world_size = int(os.environ.get("WORLD_SIZE", "1"))
    dense_model_parallel = args.tensor_parallel * args.pipeline_parallel
    if world_size % dense_model_parallel:
        raise ValueError(f"WORLD_SIZE={world_size} must be divisible by TP*PP={dense_model_parallel}")
    data_parallel = world_size // dense_model_parallel
    if data_parallel % args.expert_parallel:
        raise ValueError(f"DP={data_parallel} must be divisible by EP={args.expert_parallel}")
    if args.tensor_parallel % args.expert_tensor_parallel:
        raise ValueError(f"TP={args.tensor_parallel} must be divisible by ETP={args.expert_tensor_parallel}")
    data_parallel_batch = args.micro_batch_size * data_parallel
    if args.global_batch_size % data_parallel_batch:
        raise ValueError(
            f"Global batch size {args.global_batch_size} must be divisible by "
            f"micro_batch_size*DP={data_parallel_batch}"
        )


def main() -> None:
    """Configure and launch random-initialized 16-layer GPT-OSS pretraining."""
    args = parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    _validate_parallelism(args)

    if args.lr <= 0:
        raise ValueError("--lr must be positive")
    if args.min_lr < 0 or args.min_lr > args.lr:
        raise ValueError("--min-lr must be nonnegative and must not exceed --lr")

    tokens_per_iteration = args.seq_length * args.global_batch_size
    train_iters = math.ceil(args.train_tokens / tokens_per_iteration)
    scheduled_tokens = train_iters * tokens_per_iteration
    if args.lr_warmup_iters >= train_iters:
        raise ValueError("--lr-warmup-iters must be smaller than the computed train iterations")

    hf_model = args.hf_model.expanduser().resolve()
    if not (hf_model / "config.json").is_file():
        raise FileNotFoundError(hf_model / "config.json")
    data_args, eos_id = _load_data_args(args.dataset_root, args.data_args_path)

    save_dir = args.save_dir.expanduser().resolve()
    tensorboard_dir = args.tensorboard_dir.expanduser().resolve()
    resume_checkpoint = None
    if args.resume_checkpoint is not None:
        resume_checkpoint = args.resume_checkpoint.expanduser().resolve()
        if not resume_checkpoint.is_dir():
            raise FileNotFoundError(resume_checkpoint)

    cfg = _build_gpt_oss_20b_config(str(hf_model))

    # Single-node 8-GPU layout. EP is a sub-dimension of data parallelism.
    cfg.model.tensor_model_parallel_size = args.tensor_parallel
    cfg.model.pipeline_model_parallel_size = args.pipeline_parallel
    cfg.model.expert_model_parallel_size = args.expert_parallel
    cfg.model.expert_tensor_parallel_size = args.expert_tensor_parallel
    cfg.model.sequence_parallel = args.tensor_parallel > 1

    # Performance-team 16L GPT-OSS variant. Keep this aligned with mini_gptoss.py.
    cfg.model.num_layers = 16
    cfg.model.hidden_size = 2880
    cfg.model.num_attention_heads = 32
    cfg.model.num_query_groups = 1
    cfg.model.kv_channels = 128
    cfg.model.ffn_hidden_size = 1440
    cfg.model.num_moe_experts = 64
    cfg.model.moe_router_topk = 16
    cfg.model.moe_ffn_hidden_size = 1440
    cfg.model.moe_shared_expert_intermediate_size = 1440
    cfg.model.moe_router_load_balancing_type = "aux_loss"
    cfg.model.moe_aux_loss_coeff = 0.9

    # Attention, router, and routed experts retain bias. The model-specific layer
    # spec makes only the MCore shared expert bias-free, as required by its implementation.
    cfg.model.transformer_layer_spec = _gpt_oss_transformer_layer_spec
    cfg.model.add_bias_linear = True
    cfg.model.add_qkv_bias = True
    cfg.model.bias_activation_fusion = True
    cfg.model.window_size = (32767, 0)
    cfg.model.window_attn_skip_freq = None
    cfg.model.rotary_base = 150000
    cfg.model.yarn_rotary_scaling_factor = 64.0
    cfg.model.yarn_original_max_position_embeddings = 4096
    cfg.model.yarn_beta_fast = 32.0
    cfg.model.yarn_beta_slow = 1.0
    cfg.model.yarn_correction_range_round_to_int = False

    if args.precision == "fp8-current":
        cfg.mixed_precision = "bf16_with_fp8_current_scaling_mixed"
        cfg.model.moe_router_padding_for_fp8 = True
    elif args.precision == "mxfp8":
        cfg.mixed_precision = "bf16_with_mxfp8_mixed"
        cfg.model.moe_router_padding_for_fp8 = True
    else:
        cfg.mixed_precision = "bf16_mixed"
        cfg.model.moe_router_padding_for_fp8 = False

    if args.no_full_recompute:
        cfg.model.recompute_granularity = None
        cfg.model.recompute_method = None
        cfg.model.recompute_num_layers = None
    else:
        cfg.model.recompute_granularity = "full"
        cfg.model.recompute_method = "uniform"
        cfg.model.recompute_num_layers = 1

    cfg.model.seq_length = args.seq_length
    cfg.dataset.sequence_length = args.seq_length
    cfg.dataset.data_path = data_args
    cfg.dataset.blend = None
    cfg.dataset.split = "1,0,0"
    cfg.dataset.num_workers = args.num_workers
    cfg.dataset.num_dataset_builder_threads = max(1, args.num_workers)
    if args.dataset_cache_dir is not None:
        cfg.dataset.path_to_cache = str(args.dataset_cache_dir.expanduser().resolve())
    cfg.tokenizer.vocab_size = cfg.model.vocab_size
    cfg.tokenizer.null_tokenizer_eod_id = eos_id
    cfg.tokenizer.null_tokenizer_pad_id = GPT_OSS_PAD_TOKEN_ID

    cfg.train.train_iters = train_iters
    cfg.train.train_samples = None
    cfg.train.micro_batch_size = args.micro_batch_size
    cfg.train.global_batch_size = args.global_batch_size
    cfg.validation.eval_interval = None
    cfg.validation.eval_iters = 0

    cfg.optimizer.lr = args.lr
    cfg.optimizer.min_lr = args.min_lr
    cfg.scheduler.lr_warmup_iters = args.lr_warmup_iters
    cfg.scheduler.lr_decay_iters = train_iters
    cfg.scheduler.lr_decay_style = args.lr_decay_style
    cfg.scheduler.lr_warmup_init = 0.0
    cfg.scheduler.override_opt_param_scheduler = True

    cfg.logger.log_interval = args.log_interval
    cfg.logger.log_throughput = True
    cfg.logger.tensorboard_dir = str(tensorboard_dir)
    cfg.logger.tensorboard_log_interval = args.log_interval
    cfg.logger.log_timers_to_tensorboard = True
    cfg.logger.log_throughput_to_tensorboard = True

    cfg.checkpoint.pretrained_checkpoint = None
    cfg.checkpoint.save = str(save_dir)
    cfg.checkpoint.save_interval = args.save_interval
    cfg.checkpoint.ckpt_format = "torch_dist"
    cfg.checkpoint.fully_parallel_save = True
    cfg.checkpoint.async_save = False
    if resume_checkpoint is None:
        cfg.checkpoint.load = None
        cfg.checkpoint.load_optim = False
        cfg.checkpoint.load_rng = False
        cfg.checkpoint.finetune = False
    else:
        cfg.checkpoint.load = str(resume_checkpoint)
        cfg.checkpoint.load_optim = True
        cfg.checkpoint.load_rng = True
        cfg.checkpoint.finetune = False

    if int(os.environ.get("RANK", "0")) == 0:
        LOGGER.info(
            "Training plan: requested_tokens=%d scheduled_tokens=%d train_iters=%d "
            "tokens_per_iteration=%d weighted_shards=%d precision=%s resume=%s",
            args.train_tokens,
            scheduled_tokens,
            train_iters,
            tokens_per_iteration,
            len(data_args) // 2,
            args.precision,
            resume_checkpoint is not None,
        )
        LOGGER.info("Checkpoint directory: %s", save_dir)
        LOGGER.info("TensorBoard directory: %s", tensorboard_dir)

    pretrain(config=cfg, forward_step_func=forward_step)


if __name__ == "__main__":
    main()
